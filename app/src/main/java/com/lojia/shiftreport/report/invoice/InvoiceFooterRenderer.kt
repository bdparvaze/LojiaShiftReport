package com.lojia.shiftreport.report.invoice

import android.content.Context
import android.graphics.Canvas
import android.graphics.Paint
import com.lojia.shiftreport.util.PdfFontManager
import com.lojia.shiftreport.util.PdfPalette
import com.lojia.shiftreport.util.PdfQrCodeGenerator

/**
 * Renders the bottom footer of POS invoices.
 * Includes styled squircle QR code (ZATCA / Shift verification compliant),
 * multilingual thank-you footer notes (EN, AR, BN), and page numbering.
 */
object InvoiceFooterRenderer {

    fun drawFooter(
        canvas: Canvas,
        context: Context,
        data: InvoiceData,
        pageWidth: Float,
        pageHeight: Float,
        startY: Float,
        pageNumber: Int = 1,
        totalPages: Int = 1
    ): Float {
        var currentY = startY
        val isThermal = data.paperSize.isThermal
        val margin = if (isThermal) 12f else 32f
        val centerX = pageWidth / 2f

        // 1. QR Code
        val qrSizePx = if (isThermal) 140 else 200
        val qrContent = data.qrData.ifBlank {
            "Lojia POS Invoice #${data.invoiceNo} | Shift #${data.shiftId} | Total: ${data.payment.totalPayable} ${data.currencyCode} | VAT: ${data.vatNo}"
        }

        val qrBmp = PdfQrCodeGenerator.generateStyledQrCodeBitmap(qrContent, targetPixelSize = qrSizePx)
        if (qrBmp != null) {
            val drawQrSize = if (isThermal) 70f else 90f
            val qrLeft = centerX - (drawQrSize / 2f)
            val destRect = android.graphics.RectF(qrLeft, currentY, qrLeft + drawQrSize, currentY + drawQrSize)
            canvas.drawBitmap(qrBmp, null, destRect, null)
            currentY += drawQrSize + 10f
        }

        // 2. Multilingual Footer Notes (EN, AR, BN)
        val notePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = PdfPalette.TEXT_SECONDARY
            textAlign = Paint.Align.CENTER
            textSize = if (isThermal) 8f else 10f
        }

        // English Note
        PdfFontManager.applyTypeface(notePaint, context, data.footerNoteEn, isBold = false)
        canvas.drawText(data.footerNoteEn, centerX, currentY + 10f, notePaint)
        currentY += 13f

        // Arabic Note
        PdfFontManager.applyTypeface(notePaint, context, data.footerNoteAr, isBold = false)
        canvas.drawText(data.footerNoteAr, centerX, currentY + 10f, notePaint)
        currentY += 13f

        // Bengali Note
        PdfFontManager.applyTypeface(notePaint, context, data.footerNoteBn, isBold = false)
        canvas.drawText(data.footerNoteBn, centerX, currentY + 10f, notePaint)
        currentY += 16f

        // 3. Page Numbering
        if (!isThermal) {
            val pagePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                color = PdfPalette.TEXT_HINT
                textSize = 8.5f
                textAlign = Paint.Align.CENTER
            }
            val pageStr = "Page $pageNumber of $totalPages • Generated by Lojia POS"
            PdfFontManager.applyTypeface(pagePaint, context, pageStr, isBold = false)
            canvas.drawText(pageStr, centerX, pageHeight - 14f, pagePaint)
        }

        return currentY
    }
}
